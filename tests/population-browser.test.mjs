import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile, mkdir} from 'node:fs/promises';
import {productionEditor, state} from './editor-browser-fixture.mjs';

const fixture=JSON.parse(await readFile(new URL('./fixtures/population-analytical.json',import.meta.url),'utf8'));
test('supplied model chooser calculates through the real local worker and preserves the drawing',async t=>{
  const external=[],page=await productionEditor(t,{externalRequests:external}),before=await state(page),requests=[];
  page.on('request',request=>{if(request.url().includes('/api/populations/'))requests.push(request.url());});
  await page.locator('#open-population-model').click();
  await page.locator('#population-model-file').setInputFiles({name:'synthetic-pka7.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(fixture.complete.envelope.model))});
  await page.waitForFunction(()=>document.querySelector('#population-model-status').textContent.startsWith('Supplied-model calculation ready.'),{},{timeout:20000});
  const percentages=()=>page.locator('#population-model-chart [data-population-percentage]').evaluateAll(cells=>cells.map(cell=>Number(cell.dataset.percentage)));
  assert.deepEqual(await percentages(),[50,50]);
  assert.match(await page.locator('#population-model-chart').textContent(),/Synthetic analytical population example/);
  await page.locator('#population-model-chart [data-population-ph]').fill('8.0');
  await page.locator('#population-model-chart [data-population-form] button').click();
  const values=await percentages();assert.ok(Math.abs(values[0]-100/11)<1e-8);assert.ok(Math.abs(values[1]-1000/11)<1e-8);
  await page.locator('#population-model-chart [data-population-visible]').first().uncheck();
  assert.equal(await page.locator('#population-model-chart [data-population-visible]').first().evaluate(el=>el.getBoundingClientRect().width),18);
  assert.deepEqual(await percentages(),values);
  assert.match(await page.locator('#population-model-chart [data-population-mass]').textContent(),/hidden represented: 9\.090909/);
  assert.equal(requests.filter(url=>url.endsWith('/evaluate')).length,1,'Selection and visibility reuse the cached calculation.');
  assert.deepEqual((await state(page)).document,before.document);
  assert.equal((await state(page)).revision,before.revision);
  await mkdir(new URL('../../checks/',import.meta.url),{recursive:true});
  await page.screenshot({path:new URL('../../checks/population-model-ui.png',import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
  await page.locator('#population-title').scrollIntoViewIfNeeded();
  await page.screenshot({path:new URL('../../checks/population-model-ui-top.png',import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
  await page.locator('#close-population-model').click();
  assert.equal(await page.locator('#population-model-chart canvas').count(),0);
  await page.locator('#open-population-model').click();
  await page.locator('#population-model-file').setInputFiles({name:'incomplete.json',mimeType:'application/json',buffer:Buffer.from('{}')});
  await page.waitForFunction(()=>!document.querySelector('#choose-population-model').disabled);
  assert.notEqual(await page.locator('#population-model-status').textContent(),'Choose a complete model JSON file. Calculations stay on this computer.');
  assert.equal(await page.locator('#population-model-chart canvas').count(),0);
  assert.equal(requests.filter(url=>url.endsWith('/evaluate')).length,1,'Invalid models do not start workers.');
  assert.deepEqual((await state(page)).document,before.document);
  const injected=external.filter(url=>new URL(url).hostname==='injections.adguard.org');
  if(injected.length)t.diagnostic(`${injected.length} AdGuard injected requests blocked by the browser fixture; no system-wide network claim.`);
  assert.deepEqual(external.filter(url=>new URL(url).hostname!=='injections.adguard.org'),[]);
});
